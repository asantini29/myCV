"""
Generate the talks, outreach and education sections of the CV from data/*.yml.

The YAML files are the single source for this content: the website
(asantini29.github.io) reads the same files. Text fields use LaTeX for math
($...$) and dashes (--), and Markdown for **bold** and [links](url).
"""
import os
import re
import sys
from typing import Dict, List

import yaml

ROOT_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(ROOT_DIR, "data")
SECTIONS_DIR = os.path.join(ROOT_DIR, "cv", "cv-sections")
HEADER = "% Generated by generate_sections.py from data/{source} -- do not edit by hand.\n"
TALK_TYPES = ("invited", "contributed", "poster")
RULE = "%-----------------------\n"

MATH = re.compile(r"(\$[^$]*\$)")
LINK = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")
BOLD = re.compile(r"\*\*(.+?)\*\*")


class DataError(Exception):
    pass


def _plain(text):
    """
    Escape the LaTeX specials that can appear in prose (unless already escaped,
    e.g. \\& typed out of habit) and convert **bold**. A $ left here has no
    closing $, so it is a literal dollar sign.
    """
    escaped = re.sub(r"(?<!\\)([&%#$_])", r"\\\1", text)
    escaped = re.sub(r"(?<!\\)\^", r"\\^{}", escaped)
    return BOLD.sub(r"\\textbf{\1}", escaped)


def _with_links(text):
    """
    Convert Markdown links to \\href, escaping % and # in the URL.
    """
    out = []
    pos = 0
    for match in LINK.finditer(text):
        out.append(_plain(text[pos:match.start()]))
        url = re.sub(r"([%#])", r"\\\1", match.group(2))
        out.append("\\href{%s}{\\underline{%s}}" % (url, _plain(match.group(1))))
        pos = match.end()
    out.append(_plain(text[pos:]))
    return "".join(out)


def latex_text(text: str) -> str:
    """
    Turn a YAML text field into LaTeX, leaving $...$ math untouched.
    """
    parts = MATH.split(str(text))
    return "".join(part if i % 2 else _with_links(part) for i, part in enumerate(parts))


def _field(entry, key):
    return latex_text(entry.get(key) or "")


def _entry(args):
    return "\\cventry\n" + "".join("{%s}\n" % arg for arg in args)


def _entries(entries):
    return "\\begin{cventries}\n" + RULE + RULE.join(entries) + "\\end{cventries}\n"


def _talk(talk):
    title = "\\emph{%s}" % _field(talk, "title")
    if talk.get("format"):
        title += " -- " + _field(talk, "format")
    return _entry([_field(talk, "event"), title, _field(talk, "location"), _field(talk, "date"), ""])


def render_invited(talks: List[dict]) -> str:
    entries = [_talk(t) for t in talks if t.get("type") == "invited"]
    return (
        "\\cvsection{Talks, conferences \\& workshops}\n\n"
        "\\cvsubsection{Invited Talks}\n\n" + _entries(entries)
    )


def render_contributed(talks: List[dict]) -> str:
    parts = []
    for talk_type, heading in (("contributed", "Contributed Talks"), ("poster", "Contributed Posters")):
        entries = [_talk(t) for t in talks if t.get("type") == talk_type]
        if entries:
            parts.append("\\cvsubsection{%s}\n\n" % heading + _entries(entries))
    return "\n".join(parts)


def render_outreach(entries: List[dict]) -> str:
    rendered = []
    for item in entries:
        date = _field(item, "date")
        if item.get("language"):
            date = "\\shortstack[r]{%s \\\\ Language: %s}" % (date, _field(item, "language"))
        rendered.append(_entry([
            _field(item, "event"),
            "\\emph{%s}" % _field(item, "title"),
            _field(item, "location"),
            date,
            _field(item, "description"),
        ]))
    return "\\cvsection{Public Outreach}\n" + _entries(rendered)


def _education_entry(item):
    details = ""
    if item.get("details"):
        items = "".join("\t\\item {%s}\n" % latex_text(d) for d in item["details"])
        details = "\n\\begin{cvitems}\n" + items + "\\end{cvitems}\n"
    return _entry([
        _field(item, "degree"),
        _field(item, "institution"),
        _field(item, "location"),
        _field(item, "dates"),
        details,
    ])


def render_education(education: Dict[str, list]) -> str:
    out = "\\cvsection{Education}\n\n" + _entries(
        [_education_entry(d) for d in education.get("degrees") or []]
    )
    for key, heading in (("internships", "Internships"), ("courses", "Extracurricular courses and workshops")):
        items = education.get(key) or []
        if items:
            out += "\n\\cvsubsection{%s}\n\n" % heading + _entries([_education_entry(i) for i in items])
    return out


def _load(data_dir, name):
    with open(os.path.join(data_dir, name), encoding="utf-8") as f:
        return yaml.safe_load(f)


def _check_talk_types(talks):
    for talk in talks:
        if talk.get("type") not in TALK_TYPES:
            raise DataError("unknown type %r for %r (use one of: %s)"
                            % (talk.get("type"), talk.get("event"), ", ".join(TALK_TYPES)))


def main(data_dir: str = DATA_DIR, out_dir: str = SECTIONS_DIR) -> int:
    """
    Write the four generated section files. Returns 0 on success, 1 on a data
    error (reported on stderr with the file it came from).
    """
    outputs = (
        ("conferences.tex", "talks.yml", render_invited, list),
        ("conferences-contributed.tex", "talks.yml", render_contributed, list),
        ("outreach.tex", "outreach.yml", render_outreach, list),
        ("education.tex", "education.yml", render_education, dict),
    )
    data = {}
    contents = {}
    for target, source, render, empty in outputs:
        try:
            if source not in data:
                data[source] = _load(data_dir, source) or empty()
                if source == "talks.yml":
                    _check_talk_types(data[source])
            contents[target] = HEADER.format(source=source) + render(data[source])
        except (OSError, yaml.YAMLError, DataError, AttributeError, TypeError) as err:
            print("generate_sections.py: data/%s: %s" % (source, err), file=sys.stderr)
            return 1

    for target, text in contents.items():
        path = os.path.join(out_dir, target)
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                if f.read() == text:
                    continue
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
